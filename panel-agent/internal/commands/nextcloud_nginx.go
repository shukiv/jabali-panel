// nextcloud_nginx.go — the per-install nginx drop-in for Nextcloud
// (Discussion #1032), and how the installer finds the PHP the domain runs.
//
// The drop-in is included at server level, after the vhost's own locations:
//
//   - Deny the code, config and data trees and occ/console.php with ^~ / =
//     locations, which beat the vhost's `~ \.php$` (so e.g. /lib/base.php is a
//     404, never executed).
//   - The front controllers (/index.php/…, /remote.php/…, /public.php/…,
//     /ocs/v1.php/…, /ocs/v2.php/…) as ^~ prefixes carrying PATH_INFO. ^~ also
//     beats the vhost's regex static-cache location, which would otherwise
//     treat /index.php/apps/theming/theme/light.css as a missing file. Each
//     targets one fixed script, so no request can walk back onto an uploaded
//     file. They take 512M bodies (the pool's upload limit): the vhost's
//     default is nginx's 1M, and WebDAV uploads arrive here.
//   - CalDAV/CardDAV discovery redirects under /.well-known (= locations; the
//     ACME ^~ location keeps its own path).
//   - .mjs as JavaScript: nginx 1.24's mime.types lacks it, and a browser
//     refuses a module script served as octet-stream.

// nextcloudFrontControllers are Nextcloud's PATH_INFO entry scripts.
var nextcloudFrontControllers = []string{"index.php", "remote.php", "public.php", "ocs/v1.php", "ocs/v2.php"}

// nextcloudDeniedTrees are never served (Nextcloud's own nginx guidance).
var nextcloudDeniedTrees = []string{"build", "tests", "config", "lib", "3rdparty", "templates", "data"}

// nextcloudDeniedFiles are root files that must never be served or run.
var nextcloudDeniedFiles = []string{"/occ", "/console.php", "/.htaccess", "/.user.ini"}

func nextcloudSnippetPath(domain string) string {
	return filepath.Join(nginxJabaliDir, domain, "nextcloud.conf")
}

// nextcloudNginxConf renders the drop-in for a site whose PHP runs on socket.
func nextcloudNginxConf(socket string) string {
	var b strings.Builder
	b.WriteString("# Auto-generated by jabali-agent. Do not edit.\n")
	b.WriteString("# Nextcloud (Discussion #1032): denies, front controllers, DAV discovery, .mjs.\n")
	for _, d := range nextcloudDeniedTrees {
		fmt.Fprintf(&b, "location ^~ /%s/ { deny all; return 404; }\n", d)
	}
	for _, f := range nextcloudDeniedFiles {
		fmt.Fprintf(&b, "location = %s { deny all; return 404; }\n", f)
	}
	b.WriteString("location = /.well-known/carddav { return 301 /remote.php/dav/; }\n")
	b.WriteString("location = /.well-known/caldav { return 301 /remote.php/dav/; }\n")
	b.WriteString("location = /.well-known/webfinger { return 301 /index.php/.well-known/webfinger; }\n")
	b.WriteString("location = /.well-known/nodeinfo { return 301 /index.php/.well-known/nodeinfo; }\n")
	b.WriteString("location ~* \\.mjs$ { types { text/javascript mjs; } try_files $uri =404; }\n")
	for _, s := range nextcloudFrontControllers {
		fmt.Fprintf(&b, "location ^~ /%s/ {\n", s)
		fmt.Fprintf(&b, "    fastcgi_split_path_info ^(/%s)(/.*)$;\n", regexp.QuoteMeta(s))
		b.WriteString("    client_max_body_size 512M;\n")
		b.WriteString("    fastcgi_request_buffering off;\n")
		b.WriteString("    fastcgi_read_timeout 300s;\n")
		fmt.Fprintf(&b, "    fastcgi_pass unix:%s;\n", socket)
		b.WriteString("    include fastcgi_params;\n")
		b.WriteString("    fastcgi_param SCRIPT_FILENAME $realpath_root$fastcgi_script_name;\n")
		b.WriteString("    fastcgi_param PATH_INFO $fastcgi_path_info;\n")
		b.WriteString("    fastcgi_param modHeadersAvailable true;\n")
		b.WriteString("}\n")
	}
	return b.String()
}

func writeNextcloudNginx(ctx context.Context, domain, osUser, socket string) error {
	if !domainRegex.MatchString(domain) {
		return fmt.Errorf("invalid domain %q", domain)
	}
	if !fpmSocketRE.MatchString(socket) {
		return fmt.Errorf("invalid fpm socket %q", socket)
	}
	domainDir := filepath.Join(nginxJabaliDir, domain)
	if err := os.MkdirAll(domainDir, 0o755); err != nil {
		return fmt.Errorf("mkdir %s: %w", domainDir, err)
	}
	dest := nextcloudSnippetPath(domain)
	if err := os.WriteFile(dest, snippetWithPHPPins([]byte(nextcloudNginxConf(socket)), domain, osUser), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", dest, err)
	}
	return reloadNginxAfterSnippet(ctx, dest)
}

// removeNextcloudNginx deletes the drop-in and reloads nginx. A missing file
// is fine: idempotent.
func removeNextcloudNginx(ctx context.Context, domain string) error {
	if !domainRegex.MatchString(domain) {
		return fmt.Errorf("invalid domain %q", domain)
	}
	dest := nextcloudSnippetPath(domain)
	if err := os.Remove(dest); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("remove %s: %w", dest, err)
	}
	return reloadNginxAfterSnippet(ctx, dest)
}

// fpmPool is the PHP-FPM pool a domain's vhost passes PHP to.
type fpmPool struct {
	Socket     string
	PHPVersion string
}

var (
	// fpmSocketRE is a jabali pool socket: /run/php/jabali-<slug>/fpm.sock.
	fpmSocketRE = regexp.MustCompile(`^/run/php/jabali-([a-z_][a-z0-9_-]{0,31}(?:-php[0-9]+\.[0-9]+)?)/fpm\.sock$`)
	// vhostFastCGIPassRE finds the socket in a rendered vhost.
	vhostFastCGIPassRE = regexp.MustCompile(`(?m)^\s*fastcgi_pass\s+unix:(\S+);`)
)

// domainFPMPool reads the pool a domain's PHP runs on from the vhost the
// reconciler rendered for it, the source of truth for this domain (a
// per-version pool has its own socket, GH #329). The version comes from a
// per-version pool's slug, or else from where the user's default pool config
// lives.
func domainFPMPool(domain, osUser string) (fpmPool, error) {
	if !domainRegex.MatchString(domain) || !osUserSafeRE.MatchString(osUser) {
		return fpmPool{}, fmt.Errorf("invalid domain or user")
	}
	vhost, err := os.ReadFile(filepath.Join(nginxSitesDir, domain+".conf"))
	if err != nil {
		return fpmPool{}, fmt.Errorf("read the vhost of %s: %w", domain, err)
	}
	m := vhostFastCGIPassRE.FindSubmatch(vhost)
	if m == nil {
		return fpmPool{}, fmt.Errorf("%s does not run PHP: enable PHP on the domain first", domain)
	}
	socket := string(m[1])
	sm := fpmSocketRE.FindStringSubmatch(socket)
	if sm == nil {
		return fpmPool{}, fmt.Errorf("%s passes PHP to %s, which is not a jabali pool", domain, socket)
	}
	slug := sm[1]
	switch {
	case slug == osUser:
		confs, _ := filepath.Glob(filepath.Join(phpEtcRoot, "*", "fpm", "pool.d", "jabali-"+osUser+".conf"))
		if len(confs) != 1 {
			return fpmPool{}, fmt.Errorf("cannot tell which PHP version the pool of %s runs (%d pool configs)", osUser, len(confs))
		}
		ver := filepath.Base(filepath.Dir(filepath.Dir(filepath.Dir(confs[0]))))
		if _, _, ok := splitPHPVersion(ver); !ok {
			return fpmPool{}, fmt.Errorf("unexpected PHP version directory %q", ver)
		}
		return fpmPool{Socket: socket, PHPVersion: ver}, nil
	case strings.HasPrefix(slug, osUser+"-php"):
		ver := strings.TrimPrefix(slug, osUser+"-php")
		if _, _, ok := splitPHPVersion(ver); !ok {
			return fpmPool{}, fmt.Errorf("unexpected pool slug %q", slug)
		}
		return fpmPool{Socket: socket, PHPVersion: ver}, nil
	}
	return fpmPool{}, fmt.Errorf("%s passes PHP to another account's pool (%s)", domain, slug)
}
